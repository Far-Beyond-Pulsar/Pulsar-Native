//! The game crate (`.pulsar/build/game/`): glue only. The executable
//! (`main.rs`), the Play-In-Editor library (`lib.rs`, the `pulsar_pie_*`
//! C ABI the editor loads), the enabled plugins linked for their
//! registrations (`plugins.rs`), the scripts crates registered and the
//! script driver enabled (`setup.rs`), and the classes compiled to Rust
//! (`classes/`).

use super::root::RootManifest;
use super::{CLASS_DEPENDENCIES, GLUE_DEPENDENCIES, MANIFEST_HEADER};
use crate::error::SyncError;
use crate::model::ProjectModel;
use crate::paths;
use crate::toml_out::Doc;

const SOURCE_HEADER: &str = "Generated by Pulsar: every sync rewrites it. Game code belongs in a\n\
//! scripts crate (scripts/<name>/), plugins and the project's name in Pulsar.toml.";

pub(super) fn render(
    model: &ProjectModel,
    root: &RootManifest,
) -> Result<Vec<(String, String)>, SyncError> {
    let file = |name: &str| format!("{}/{name}", paths::GAME_DIR);
    let mut files = vec![
        (file("Cargo.toml"), manifest(model, root)?),
        (file("src/main.rs"), main_rs(model)),
        (file("src/lib.rs"), lib_rs(model)),
        (file("src/plugins.rs"), plugins_rs(model)),
        (file("src/setup.rs"), setup_rs(model)),
    ];
    if !model.classes.is_empty() {
        files.push((file("src/classes/mod.rs"), classes_mod_rs(model)));
        for class in &model.classes {
            files.push((
                file(&format!("src/classes/{}.rs", class.module)),
                class.source.clone(),
            ));
        }
    }
    Ok(files)
}

fn manifest(model: &ProjectModel, root: &RootManifest) -> Result<String, SyncError> {
    let workspace = |name: &str, features: &[&str]| -> Result<toml::Value, SyncError> {
        if !root.dependencies.contains_key(name) {
            return Err(SyncError::Sdk(format!(
                "the game crate depends on `{name}`, which the engine SDK does not provide"
            )));
        }
        let mut spec = toml::Table::new();
        spec.insert("workspace".into(), toml::Value::Boolean(true));
        if !features.is_empty() {
            spec.insert(
                "features".into(),
                toml::Value::Array(features.iter().map(|f| (*f).into()).collect()),
            );
        }
        Ok(toml::Value::Table(spec))
    };

    let mut doc = Doc::new();
    doc.comment(MANIFEST_HEADER)
        .section(&["package"])
        .str("name", &model.package)
        .str("version", &model.version)
        .str("edition", "2021")
        .entry("publish", &toml::Value::Boolean(false))
        .section(&["lib"])
        .comment("The Play-In-Editor library the editor loads (and an rlib for tools).")
        .str("name", &model.lib)
        .str("path", "src/lib.rs")
        .entry(
            "crate-type",
            &toml::Value::Array(vec!["cdylib".into(), "rlib".into()]),
        )
        .array_section("bin")
        .comment("The game executable, named after the project.")
        .str("name", &model.bin)
        .str("path", "src/main.rs");

    doc.section(&["dependencies"]);
    for (name, features) in GLUE_DEPENDENCIES {
        doc.entry(name, &workspace(name, features)?);
    }
    if !model.plugin_roots.is_empty() {
        doc.comment("The enabled plugins (Pulsar.toml [plugins]).");
        for name in &model.plugin_roots {
            doc.entry(name, &workspace(name, &[])?);
        }
    }
    if !model.scripts.is_empty() {
        doc.comment("The scripts crates (scripts/).");
        for script in &model.scripts {
            let mut spec = toml::Table::new();
            spec.insert(
                "path".into(),
                paths::relative(paths::GAME_DIR, &format!("{}/{}", paths::SCRIPTS_DIR, script.dir))
                    .into(),
            );
            doc.entry(&script.name, &toml::Value::Table(spec));
        }
    }
    if !model.classes.is_empty() {
        doc.comment("What the classes compiled to Rust name.");
        for (name, features) in CLASS_DEPENDENCIES {
            if GLUE_DEPENDENCIES.iter().any(|(glue, _)| glue == name) {
                continue;
            }
            doc.entry(name, &workspace(name, features)?);
        }
    }
    Ok(doc.finish())
}

/// The modules both the executable and the library compile.
fn modules(model: &ProjectModel) -> String {
    let mut out = String::from("mod plugins;\nmod setup;\n");
    if !model.classes.is_empty() {
        out.push_str(
            "// Not yet run: placed instances of a class run its script until the\n\
             // script driver can bind them to the class's Rust form.\n\
             #[allow(dead_code)]\nmod classes;\n",
        );
    }
    out
}

fn main_rs(model: &ProjectModel) -> String {
    format!(
        r#"//! The game executable. {SOURCE_HEADER}
//!
//! The game finds its content at start-up (`pulsar_game::standalone`):
//! `Content/` beside the executable when packaged, the project around it
//! otherwise. `--headless --frames N` runs without a window; `--content DIR`
//! reads content from DIR.

{modules}
fn main() {{
    tracing_subscriber::fmt()
        .with_env_filter(std::env::var("RUST_LOG").unwrap_or_else(|_| "info".into()))
        .init();
    std::process::exit(pulsar_game::standalone::run(setup::setup));
}}
"#,
        modules = modules(model),
    )
}

fn lib_rs(model: &ProjectModel) -> String {
    format!(
        r#"//! The Play-In-Editor library. {SOURCE_HEADER}
//!
//! Exports the `pulsar_pie_*` C ABI the editor loads when Play is pressed.
//! Each entry point catches panics (unwinding across the boundary is
//! undefined behaviour) and delegates to `pulsar_game::embed`.

use pulsar_game::embed;
use pulsar_pie_abi::{{EngineContext, InputEvent, INIT_ERR, PIE_ABI_VERSION}};

{modules}
/// The ABI revision this game was built against; the editor refuses a
/// library of another revision and rebuilds it.
#[no_mangle]
pub extern "C" fn pulsar_pie_abi_version() -> u64 {{
    PIE_ABI_VERSION
}}

/// Build the embedded game on the editor's GPU device. Returns `1` on
/// success (and writes `ctx.out_texture`), `0` on failure.
///
/// # Safety
/// `ctx` must point at a valid, host-populated `EngineContext`.
#[no_mangle]
pub unsafe extern "C" fn pulsar_pie_init(ctx: *mut EngineContext) -> u32 {{
    std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| unsafe {{
        embed::pie_init(ctx, setup::setup)
    }}))
    .unwrap_or(INIT_ERR)
}}

/// Advance the simulation and render one frame into the offscreen target.
#[no_mangle]
pub extern "C" fn pulsar_pie_tick(delta_time: f32) {{
    let _ = std::panic::catch_unwind(|| embed::pie_tick(delta_time));
}}

/// Resize the offscreen render target.
#[no_mangle]
pub extern "C" fn pulsar_pie_resize(width: u32, height: u32) {{
    let _ = std::panic::catch_unwind(|| embed::pie_resize(width, height));
}}

/// Forward one input event from the editor.
///
/// # Safety
/// `ev` must be a valid pointer to an `InputEvent` for the duration of the call.
#[no_mangle]
pub unsafe extern "C" fn pulsar_pie_input(ev: *const InputEvent) {{
    let _ = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| unsafe {{
        embed::pie_input(ev)
    }}));
}}

/// Tear down the embedded game before the editor unloads the library.
#[no_mangle]
pub extern "C" fn pulsar_pie_shutdown() {{
    let _ = std::panic::catch_unwind(embed::pie_shutdown);
}}

/// An asset was updated in the editor (a class was saved): reload it.
///
/// # Safety
/// Each pointer/length pair must be a valid UTF-8 range or null.
#[no_mangle]
pub unsafe extern "C" fn pulsar_pie_asset_updated(
    kind: *const u8,
    kind_len: usize,
    id: *const u8,
    id_len: usize,
    path: *const u8,
    path_len: usize,
) {{
    let _ = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| unsafe {{
        embed::pie_asset_updated(kind, kind_len, id, id_len, path, path_len)
    }}));
}}

/// The session's event debug snapshot (JSON) for the editor's events panel.
///
/// # Safety
/// `out` must be valid for `capacity` bytes of writes (or `capacity` 0).
#[no_mangle]
pub unsafe extern "C" fn pulsar_pie_events_snapshot(out: *mut u8, capacity: usize) -> usize {{
    std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| unsafe {{
        embed::pie_events_snapshot(out, capacity)
    }}))
    .unwrap_or(0)
}}

/// Simulation control for the editor's pause and step buttons.
#[no_mangle]
pub extern "C" fn pulsar_pie_control(command: u32, arg: u64) -> u64 {{
    std::panic::catch_unwind(|| embed::pie_control(command, arg)).unwrap_or(0)
}}

/// Script problems raised since the last call (JSON) for the problems panel.
///
/// # Safety
/// `out` must be valid for `capacity` bytes of writes (or `capacity` 0).
#[no_mangle]
pub unsafe extern "C" fn pulsar_pie_take_problems(out: *mut u8, capacity: usize) -> usize {{
    std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| unsafe {{
        embed::pie_take_problems(out, capacity)
    }}))
    .unwrap_or(0)
}}

/// The session's event hub for editor plugins (a Gamma `RawBus`).
///
/// # Safety
/// `out` must be valid for `out_size` bytes of writes.
#[no_mangle]
pub unsafe extern "C" fn pulsar_pie_event_bus(out: *mut std::ffi::c_void, out_size: usize) -> u32 {{
    std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| unsafe {{
        embed::pie_event_bus(out, out_size)
    }}))
    .unwrap_or(0)
}}
"#,
        modules = modules(model),
    )
}

fn plugins_rs(model: &ProjectModel) -> String {
    let mut out = format!(
        "//! The enabled plugins (Pulsar.toml `[plugins]`), linked for their\n\
         //! registrations. A disabled plugin is not linked: its kind is absent\n\
         //! from the game. {SOURCE_HEADER}\n"
    );
    if !model.plugin_roots.is_empty() {
        out.push('\n');
    }
    for root in &model.plugin_roots {
        out.push_str(&format!("use {} as _;\n", rust_ident(root)));
    }
    out
}

fn setup_rs(model: &ProjectModel) -> String {
    let mut registrations = String::new();
    for script in &model.scripts {
        registrations.push_str(&format!(
            "    // scripts/{dir}\n    {krate}::register_scripts(game)?;\n",
            dir = script.dir,
            krate = rust_ident(&script.name),
        ));
    }
    format!(
        r#"//! The game's setup, run once before the first frame by the executable
//! and by Play-In-Editor. {SOURCE_HEADER}

use pulsar_game::prelude::*;

/// Register each scripts crate's actors (its `register_scripts`), then
/// enable the script driver: every placed class instance runs its class's
/// compiled script, from level load, Play-In-Editor placement or a
/// script's spawn; global scripts are listed in `Pulsar/scripting.json`.
pub fn setup(game: &mut TickLoop) -> Result<(), String> {{
{registrations}    game.enable_project_scripting()?;
    Ok(())
}}
"#
    )
}

fn classes_mod_rs(model: &ProjectModel) -> String {
    let mut out = format!(
        "//! The classes whose compile target is Rust, generated from their\n\
         //! compiled modules. {SOURCE_HEADER}\n\n"
    );
    for class in &model.classes {
        out.push_str(&format!("pub mod {};\n", class.module));
    }
    out
}

/// Cargo names may have hyphens; Rust paths spell them with underscores.
fn rust_ident(cargo_name: &str) -> String {
    cargo_name.replace('-', "_")
}
