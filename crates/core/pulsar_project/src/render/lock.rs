//! Seeding the project's `Cargo.lock` from the engine's, so a game resolves
//! every crate the engine uses at the engine's version (a game that starts
//! without a lockfile would resolve today's newest releases, which the
//! engine has never been built with).
//!
//! The lockfile is Cargo's: sync seeds it when the project has none or the
//! engine changed, and Cargo prunes and extends it on the next build.
//! Seeding keeps the project's own locked crates that the engine does not
//! have (a scripts crate's dependencies), and gives the engine's version
//! wherever both have a crate. Path packages carry no source and are
//! re-derived by Cargo, so the project's are dropped.

/// The first lines Cargo writes.
const HEADER: &str = "# This file is automatically @generated by Cargo.\n\
# It is not intended for manual editing.\n";

pub fn seed(engine_lock: &str, project_lock: Option<&str>) -> Result<String, String> {
    let engine: toml::Table = toml::from_str(engine_lock).map_err(|e| format!("the engine's Cargo.lock: {e}"))?;
    let mut packages: Vec<toml::Value> = packages(&engine);
    let key = |p: &toml::Value| {
        (
            str_of(p, "name").to_owned(),
            str_of(p, "version").to_owned(),
            str_of(p, "source").to_owned(),
        )
    };
    // A lock entry names a dependency by bare name while only one version of
    // it is locked: keeping a project's other version of a crate the engine
    // locks would make the engine's entries ambiguous, so the engine's
    // crates are the engine's alone.
    let engine_names: std::collections::BTreeSet<String> = packages
        .iter()
        .map(|p| str_of(p, "name").to_owned())
        .collect();

    let mut kept: Vec<toml::Value> = Vec::new();
    if let Some(project_lock) = project_lock {
        // A project lockfile that does not parse is replaced: Cargo would
        // refuse it anyway.
        if let Ok(project) = toml::from_str::<toml::Table>(project_lock) {
            kept = self::packages(&project)
                .into_iter()
                .filter(|p| !str_of(p, "source").is_empty())
                .filter(|p| !engine_names.contains(str_of(p, "name")))
                .collect();
        }
    }
    // The same applies to the kept entries' own references: one naming a
    // crate by bare name that is now locked at two versions is dropped
    // (Cargo resolves it again), until none is left.
    loop {
        let mut versions: std::collections::BTreeMap<&str, usize> = Default::default();
        for p in packages.iter().chain(&kept) {
            *versions.entry(str_of(p, "name")).or_default() += 1;
        }
        let ambiguous = |p: &toml::Value| {
            p.get("dependencies")
                .and_then(toml::Value::as_array)
                .into_iter()
                .flatten()
                .filter_map(toml::Value::as_str)
                .any(|dep| !dep.contains(' ') && versions.get(dep).copied().unwrap_or(0) > 1)
        };
        let before = kept.len();
        let retained: Vec<toml::Value> = kept.iter().filter(|p| !ambiguous(p)).cloned().collect();
        drop(versions);
        kept = retained;
        if kept.len() == before {
            break;
        }
    }
    packages.extend(kept);
    packages.sort_by_key(|p| key(p));

    let mut doc = toml::Table::new();
    if let Some(version) = engine.get("version") {
        doc.insert("version".into(), version.clone());
    }
    doc.insert("package".into(), toml::Value::Array(packages));
    let body = toml::to_string(&doc).map_err(|e| e.to_string())?;
    Ok(format!("{HEADER}{body}"))
}

fn packages(lock: &toml::Table) -> Vec<toml::Value> {
    lock.get("package")
        .and_then(toml::Value::as_array)
        .cloned()
        .unwrap_or_default()
}

fn str_of<'a>(package: &'a toml::Value, key: &str) -> &'a str {
    package.get(key).and_then(toml::Value::as_str).unwrap_or("")
}

#[cfg(test)]
mod tests {
    use super::*;

    const ENGINE: &str = r#"
version = 4

[[package]]
name = "serde"
version = "1.0.228"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aa"

[[package]]
name = "pulsar_game"
version = "0.1.0"
dependencies = ["serde"]
"#;

    const PROJECT: &str = r#"
version = 4

[[package]]
name = "serde"
version = "1.0.100"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "old"

[[package]]
name = "rand"
version = "0.8.5"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bb"

[[package]]
name = "my_scripts"
version = "0.1.0"
"#;

    #[test]
    fn the_engine_wins_and_the_project_keeps_its_own() {
        let out = seed(ENGINE, Some(PROJECT)).unwrap();
        assert!(out.starts_with(HEADER));
        let lock: toml::Table = toml::from_str(&out).unwrap();
        assert_eq!(lock["version"].as_integer(), Some(4));
        let names: Vec<(String, String)> = packages(&lock)
            .iter()
            .map(|p| (str_of(p, "name").to_owned(), str_of(p, "version").to_owned()))
            .collect();
        assert!(names.contains(&("serde".into(), "1.0.228".into())));
        assert!(names.contains(&("rand".into(), "0.8.5".into())));
        assert!(names.contains(&("pulsar_game".into(), "0.1.0".into())));
        assert!(
            !names.iter().any(|(n, _)| n == "my_scripts"),
            "project path packages are Cargo's to re-derive"
        );
        assert!(
            !names.contains(&("serde".into(), "1.0.100".into())),
            "the engine's crates have only the engine's version"
        );
        assert_eq!(seed(ENGINE, Some(&out)).unwrap(), out, "seeding is stable");
    }
}
