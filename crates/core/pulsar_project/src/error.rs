//! Why a sync failed. A sync that fails writes nothing it has not finished:
//! files are replaced atomically and the records are written last.

use std::path::PathBuf;

#[derive(Debug, thiserror::Error)]
pub enum SyncError {
    #[error("{0} is not a Pulsar project: it has no Pulsar.toml")]
    NotAProject(PathBuf),

    #[error("Pulsar.toml: {0}")]
    Descriptor(String),

    #[error("the engine SDK: {0}")]
    Sdk(String),

    #[error("{path}: {message}")]
    Io { path: PathBuf, message: String },

    #[error("scripts crate `{dir}`: {message}")]
    ScriptCrate { dir: String, message: String },

    #[error(
        "{path} exists and was not generated by Pulsar, so it is not replaced \
         (a project from before generated projects needs migrating)"
    )]
    Unowned { path: String },
}

impl SyncError {
    pub(crate) fn io(path: impl Into<PathBuf>, error: impl std::fmt::Display) -> Self {
        Self::Io {
            path: path.into(),
            message: format!("{error:#}"),
        }
    }
}
